#!/usr/bin/env python3
# The compressed sprite format's codes (MAME 0.289 gunpey.cpp, hn[]) as the casez body of rtl/gunpey_huff.svh: the bit reader's window
# holds the next bit to be read in bit 0, so a code's first character is bit 0. Output fields: {len[3:0], func[2:0], abits[3:0], n[3:0]}.
#   python3 tools/gen_huff.py > rtl/gunpey_huff.svh
NEW, PREV, COPY, PLUS, MINUS = 0, 1, 2, 3, 4
hn = [
    ("11", NEW, 8, 1), ("10111", NEW, 8, 2), ("10110011", NEW, 8, 3), ("1010011000", NEW, 8, 4), ("1010101010000", NEW, 8, 5),
    ("101010001011110", NEW, 8, 6), ("101010010101110", NEW, 8, 7), ("101010010101111", NEW, 8, 8), ("101010010101100", NEW, 8, 9),
    ("10101000101100", NEW, 8, 10), ("101010010101101", NEW, 8, 11), ("10101000101101", NEW, 8, 12),
    ("0", PREV, 4, 1), ("100", PREV, 4, 2), ("101011", PREV, 4, 3), ("1010010", PREV, 4, 4), ("101010100", PREV, 4, 5),
    ("1010100100", PREV, 4, 6), ("10101010110", PREV, 4, 7), ("10100111000", PREV, 4, 8), ("101010101001", PREV, 4, 9),
    ("101001111000", PREV, 4, 10), ("101010010100", PREV, 4, 11), ("1010011001", PREV, 4, 12),
    ("101101", COPY, 0, 2), ("10101011", COPY, 0, 3), ("101010011", COPY, 0, 4), ("101001101", COPY, 0, 5), ("1010011111", COPY, 0, 6),
    ("1010100011", COPY, 0, 7), ("10101000100", COPY, 0, 8), ("101010101111", COPY, 0, 9), ("101001110010", COPY, 0, 10),
    ("1010011100111", COPY, 0, 11), ("101100101", COPY, 0, 12),
    ("1011000", PLUS, 0, 2), ("101010000", PLUS, 0, 3), ("10101001011", PLUS, 0, 4), ("101010001010", PLUS, 0, 5),
    ("1010101011101", PLUS, 0, 6), ("1010101011100", PLUS, 0, 7), ("1010011110010", PLUS, 0, 8), ("10101000101110", PLUS, 0, 9),
    ("101010001011111", PLUS, 0, 10), ("1010011110011", PLUS, 0, 11),
    ("101000", MINUS, 0, 2), ("101100100", MINUS, 0, 3), ("1010011101", MINUS, 0, 4), ("10101010101", MINUS, 0, 5),
    ("101001111011", MINUS, 0, 6), ("101001111010", MINUS, 0, 7), ("1010101010001", MINUS, 0, 8), ("1010011100110", MINUS, 0, 9),
    ("10101001010101", MINUS, 0, 10), ("10101001010100", MINUS, 0, 11),
]
# the codes form a prefix code (else the casez order would matter)
for i, a in enumerate(hn):
    for j, b in enumerate(hn):
        assert i == j or not b[0].startswith(a[0]), (a, b)
print("// generated by tools/gen_huff.py from MAME 0.289 gunpey.cpp's hn[]: the symbol decoder's casez items")
print("// win[14:0]: the next 15 bits, the next to be read in bit 0;  sym = {len[3:0], func[2:0], abits[3:0], n[3:0]}")
for code, func, abits, n in hn:
    pat = "?" * (15 - len(code)) + code[::-1]
    print(f"15'b{pat}: sym = {{4'd{len(code)}, 3'd{func}, 4'd{abits}, 4'd{n}}};")
